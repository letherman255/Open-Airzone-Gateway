"""Generate docs/openapi.yaml from the route table below (keep it in line with firmware/core/src/api.rs).

usage: python -I tools/gen_openapi.py [--check]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "docs", "openapi.yaml")

# (method, path, access, summary)  access: public | token | dev (token + developer mode) | master (token + master mode)
ROUTES = [
    ("get", "/info", "public", "Gateway facts: version, board, mode, MQTT, Wi-Fi, uptime"),
    ("get", "/systems", "public", "Centrals and zones found on the bus"),
    ("get", "/systems/{system}", "public", "System, IAQ sensor and outlet values of one central"),
    ("get", "/systems/{system}/zones/{zone}", "public", "Values of one zone"),
    ("get", "/catalogue", "public", "The register catalogue the page renders"),
    ("get", "/params/{id}", "public", "One parameter (query: system, zone, outlet): value, raw registers, writable"),
    ("post", "/password", "public", "Set the admin password (first time) or change it (body: old, new)"),
    ("post", "/login", "public", "Open a session (body: password); answers a bearer token"),
    ("post", "/logout", "token", "Close the session"),
    ("post", "/params/{id}", "master", "Write a parameter (body: system, zone|outlet, value, confirm for dangerous settings); answers 202 + write id"),
    ("get", "/writes/{id}", "token", "Result of a queued write: queued, applied, rejected, no_answer, unverified"),
    ("get", "/journal", "token", "Configuration changes made through the gateway"),
    ("post", "/journal/{index}/undo", "master", "Write back the old value of a journal entry"),
    ("get", "/settings", "token", "Gateway settings, secrets redacted"),
    ("post", "/settings", "token", "Change network / MQTT / calendar settings (secrets are write-only)"),
    ("get", "/diagnostics", "token", "Everything needed for a bug report, without secrets"),
    ("get", "/backup", "token", "Every configuration setting of the installation, as a restorable file"),
    ("post", "/restore", "master", "Write back a backup file (body: the file + confirm: [words]); answers queued write ids and skipped entries"),
    ("get", "/tokens", "token", "API token names"),
    ("post", "/tokens", "token", "Create an API token (body: name); the token is shown once"),
    ("delete", "/tokens/{name}", "token", "Revoke an API token"),
    ("post", "/dev", "token", "Developer mode on/off (body: on)"),
    ("get", "/log", "token", "Firmware log level"),
    ("post", "/log", "token", "Set the firmware log level (body: level = error|warn|info|debug)"),
    ("post", "/mode", "token", "Switch listen / master mode (body: mode); restarts the gateway"),
    ("post", "/rediscover", "token", "Search centrals and zones again"),
    ("post", "/restart", "token", "Restart the gateway"),
    ("get", "/registry", "dev", "Every known register of every central"),
    ("get", "/raw/{addr}/{reg}", "dev", "Raw registers (query: count)"),
    ("post", "/raw/write", "dev", "Raw write (body: addr, reg, value | and, or, confirm); dangerous bits need the confirmation; master mode only"),
    ("post", "/ota", "token", "Firmware upload (raw image body); the gateway restarts on the new image"),
    ("post", "/ota/confirm", "token", "Confirm the new image after an upload (otherwise it rolls back after 180 s)"),
    ("get", "/ws", "public", "WebSocket every 2 s: values (device states), events (new gateway events), and in developer mode frames (bus frames) and registers (changed registers)"),
]

ACCESS = {
    "public": "No authentication.",
    "token": "Bearer token (session or API token).",
    "dev": "Bearer token and developer mode on.",
    "master": "Bearer token and master mode (409 in listen mode).",
}


def render():
    out = [
        "# generated by tools/gen_openapi.py, do not edit",
        "openapi: 3.0.3",
        "info:",
        "  title: open-airzone-gateway local API",
        "  version: '1'",
        "  description: Local HTTP API of the gateway. JSON in, JSON out. See docs/api.md.",
        "servers:",
        "  - url: http://{host}/api/v1",
        "    variables:",
        "      host:",
        "        default: airzone-gw.local",
        "components:",
        "  securitySchemes:",
        "    bearer:",
        "      type: http",
        "      scheme: bearer",
        "paths:",
    ]
    paths = {}
    for method, path, access, summary in ROUTES:
        paths.setdefault(path, []).append((method, access, summary))
    for path, ops in paths.items():
        out.append(f"  {path}:")
        for method, access, summary in ops:
            out.append(f"    {method}:")
            out.append(f"      summary: \"{summary}\"")
            out.append(f"      description: \"{ACCESS[access]}\"")
            if access != "public":
                out.append("      security:")
                out.append("        - bearer: []")
            params = [p[1:-1] for p in path.split("/") if p.startswith("{")]
            if params:
                out.append("      parameters:")
                for p in params:
                    out.append(f"        - name: {p}")
                    out.append("          in: path")
                    out.append("          required: true")
                    out.append("          schema:")
                    out.append("            type: string")
            out.append("      responses:")
            out.append("        '200':")
            out.append("          description: OK")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            sys.exit(0 if f.read() == text else "docs/openapi.yaml is stale: run python -I tools/gen_openapi.py")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote docs/openapi.yaml")
