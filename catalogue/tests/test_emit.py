import os
import subprocess
import sys

from generator.emit import OUTPUTS, emit_all
from generator.schema import load

HERE = os.path.dirname(__file__)
CAT = os.path.join(HERE, "..")
REPO = os.path.join(CAT, "..")
REGISTERS = os.path.join(CAT, "registers.toml")

MINI = '''
[[param]]
id = "zone.setpoint"
scope = "zone"
reg = 3
kind = "number"
access = "rw"
tier = 1
confidence = "confirmed"
evidence = "test"
scale = 0.1
unit = "°C"
ha = { component = "climate", role = "target_temperature" }
ui = { screen = "zones", section = "Zone", order = 30, label = "Setpoint" }
'''


def mini(tmp_path):
    p = tmp_path / "c.toml"
    p.write_text(MINI, encoding="utf-8")
    return load(str(p))


def test_emit_rust_contains_param(tmp_path):
    files = emit_all(mini(tmp_path))
    rust = files["firmware/core/src/catalogue_gen.rs"]
    assert 'id: "zone.setpoint"' in rust
    assert "scale: 0.1" in rust


def test_emit_json_and_markdown(tmp_path):
    files = emit_all(mini(tmp_path))
    assert '"id": "zone.setpoint"' in files["web/catalogue.json"]
    assert "°C" in files["web/catalogue.json"]
    md = files["docs/registers.md"]
    assert md.startswith("<!-- generated by catalogue/generator, do not edit -->")
    assert "| zone.setpoint |" in md


def test_emit_is_deterministic():
    a = emit_all(load(REGISTERS))
    b = emit_all(load(REGISTERS))
    assert a == b
    assert sorted(a) == sorted(OUTPUTS)


def test_invalid_catalogue_exit_1(tmp_path):
    p = tmp_path / "bad.toml"
    p.write_text(MINI.replace('evidence = "test"', 'evidence = ""'), encoding="utf-8")
    r = subprocess.run([sys.executable, "-m", "generator", str(p), "--out", str(tmp_path)], cwd=CAT,
                       capture_output=True, text=True)
    assert r.returncode == 1
    assert "zone.setpoint: rw needs evidence" in r.stderr


def test_generated_files_up_to_date():
    files = emit_all(load(REGISTERS))
    for rel, text in files.items():
        with open(os.path.join(REPO, rel), encoding="utf-8", newline="") as f:
            assert f.read() == text, f"{rel} is stale: run python -m generator registers.toml --out .."
