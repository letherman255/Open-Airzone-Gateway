import os

DOCS = os.path.join(os.path.dirname(__file__), "..", "..", "docs")


def test_registers_md_is_generated():
    with open(os.path.join(DOCS, "registers.md"), encoding="utf-8") as f:
        assert f.readline().strip() == "<!-- generated by catalogue/generator, do not edit -->"


def test_developer_docs_exist():
    for name in ("protocol.md", "contributing.md", "development.md"):
        assert os.path.getsize(os.path.join(DOCS, name)) > 500, name
