"""Turn the validated catalogue into the files the firmware, the web page and the docs use."""
from __future__ import annotations

import json

from .schema import Param

OUTPUTS = ("firmware/core/src/catalogue_gen.rs", "web/catalogue.json", "docs/registers.md")
HEADER = "generated by catalogue/generator, do not edit"

_SCOPE = {"system": "System", "zone": "Zone", "iaq": "Iaq", "outlet": "Outlet"}
_KIND = {"number": "Number", "enum": "Enum", "bool": "Bool", "text": "Text", "command": "Command"}
_CONF = {"confirmed": "Confirmed", "matched": "Matched", "hypothesis": "Hypothesis"}
_REQ = {"iaq_present": "IaqPresent", "vmc_on": "VmcOn", "ionizer": "Ionizer"}


def _f(x: float) -> str:
    s = repr(float(x))
    return s if "." in s or "e" in s else s + ".0"


def _s(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _opt(x, fmt) -> str:
    return "None" if x is None else f"Some({fmt(x)})"


def emit_rust(params: list[Param]) -> str:
    out = [f"// {HEADER}", "use crate::catalogue::*;", "", "pub static PARAMS: &[Param] = &["]
    for p in sorted(params, key=lambda p: p.id):
        values = ", ".join(f"({k}, {_s(v)})" for k, v in sorted(p.values.items()))
        danger = "None" if p.danger is None else (
            f"Some(Danger {{ level: {_s(p.danger.level)}, warning: {_s(p.danger.warning)}, confirm: {_s(p.danger.confirm)} }})")
        out += [
            "    Param {",
            f"        id: {_s(p.id)},",
            f"        scope: Scope::{_SCOPE[p.scope]},",
            f"        reg: 0x{p.reg:04X},",
            f"        lo: {p.lo},",
            f"        hi: {p.hi},",
            f"        kind: Kind::{_KIND[p.kind]},",
            f"        scale: {_f(p.scale)},",
            f"        offset: {_f(p.offset)},",
            f"        unit: {_s(p.unit)},",
            f"        values: &[{values}],",
            f"        min: {_opt(p.min, _f)},",
            f"        max: {_opt(p.max, _f)},",
            f"        length: {p.length},",
            f"        writable: {'true' if p.access == 'rw' else 'false'},",
            f"        mask_write: {'true' if p.write == '16' else 'false'},",
            f"        tier: {p.tier},",
            f"        confidence: Confidence::{_CONF[p.confidence]},",
            f"        requires: {_opt(p.requires, lambda r: 'Requires::' + _REQ[r])},",
            f"        danger: {danger},",
            f"        ha_component: {_s((p.ha or {}).get('component', ''))},",
            f"        ha_role: {_s((p.ha or {}).get('role', ''))},",
            f"        label: {_s(p.ui.get('label', p.id))},",
            "    },",
        ]
    out += ["];", ""]
    return "\n".join(out)


def emit_json(params: list[Param]) -> str:
    items = []
    for p in sorted(params, key=lambda p: p.id):
        items.append({
            "id": p.id, "scope": p.scope, "reg": p.reg, "bits": [p.lo, p.hi], "kind": p.kind, "scale": p.scale,
            "offset": p.offset, "unit": p.unit, "values": {str(k): v for k, v in sorted(p.values.items())},
            "min": p.min, "max": p.max, "length": p.length, "writable": p.access == "rw", "tier": p.tier,
            "confidence": p.confidence, "requires": p.requires,
            "danger": None if p.danger is None else {"level": p.danger.level, "warning": p.danger.warning,
                                                     "confirm": p.danger.confirm},
            "ha": p.ha, "ui": p.ui,
        })
    return json.dumps({"version": 1, "params": items}, ensure_ascii=False, indent=1) + "\n"


def _encoding(p: Param) -> str:
    if p.kind == "enum":
        return ", ".join(f"{k} {v}" for k, v in sorted(p.values.items()))
    if p.kind == "number":
        parts = []
        if p.scale != 1:
            parts.append(f"×{p.scale:g}")
        if p.offset:
            parts.append(f"{p.offset:+g}")
        if p.unit:
            parts.append(p.unit)
        return " ".join(parts) or "raw"
    if p.kind == "text":
        return f"ASCII, {p.length} registers"
    return p.kind


def emit_markdown(params: list[Param]) -> str:
    out = [f"<!-- {HEADER} -->", "# Register catalogue", "",
           "Zone registers are offsets in the zone block (zone n starts at n × 0x100); outlet registers are offsets in "
           "the outlet block (outlet n starts at 0x2900 + 0x100 × (n − 1)); system and IAQ registers are absolute.", ""]
    for scope in ("system", "zone", "iaq", "outlet"):
        rows = sorted((p for p in params if p.scope == scope), key=lambda p: (p.reg, p.lo, p.id))
        if not rows:
            continue
        out += [f"## {scope}", "", "| id | register | bits | encoding | access | tier | confidence | evidence |",
                "|---|---|---|---|---|---|---|---|"]
        for p in rows:
            bits = f"{p.lo}" if p.lo == p.hi else f"{p.lo}-{p.hi}"
            out.append(f"| {p.id} | 0x{p.reg:04X} | {bits} | {_encoding(p)} | {p.access} | {p.tier} | {p.confidence} | "
                       f"{p.evidence.replace('|', '/')} |")
        out.append("")
    return "\n".join(out)


def emit_all(params: list[Param]) -> dict[str, str]:
    return dict(zip(OUTPUTS, (emit_rust(params), emit_json(params), emit_markdown(params))))
